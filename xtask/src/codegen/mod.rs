//! Generates Rust protocol types from `schema.json` and `schema.ts`.
//!
//! Pipeline: verify the lock → parse JSON Schema `$defs` into an IR
//! ([`ir`]) using the per-revision overrides → annotate deprecations found in
//! the TypeScript JSDoc ([`deprecations`]) → emit tokens ([`emit`]) → format
//! with `prettyplease`.

mod deprecations;
mod docs;
mod emit;
mod ir;
mod names;
mod overrides;

use std::path::Path;

use anyhow::{Context, Result, bail};

use crate::fetch;
use crate::revisions::{REVISIONS, Revision};

pub(crate) fn run(root: &Path, check: bool) -> Result<()> {
    let mut stale = Vec::new();
    for revision in REVISIONS {
        let generated = generate(root, *revision)
            .with_context(|| format!("generating revision {}", revision.name))?;
        let out = root
            .join("crates/mcpsdkrust-spec/src")
            .join(revision.module)
            .join("mod.rs");
        if check {
            let current = std::fs::read_to_string(&out).unwrap_or_default();
            if normalize(&current) != normalize(&generated) {
                stale.push(out.display().to_string());
            }
        } else {
            if let Some(parent) = out.parent() {
                std::fs::create_dir_all(parent)?;
            }
            std::fs::write(&out, generated)
                .with_context(|| format!("writing {}", out.display()))?;
            println!("generated {}", out.display());
        }
    }
    if !stale.is_empty() {
        bail!(
            "generated code is stale: {}\nrun `cargo xtask codegen`",
            stale.join(", ")
        );
    }
    Ok(())
}

fn generate(root: &Path, revision: Revision) -> Result<String> {
    fetch::verify(root, revision)?;
    let dir = root.join("spec").join(revision.name);
    let schema: serde_json::Value =
        serde_json::from_str(&std::fs::read_to_string(dir.join("schema.json"))?)?;
    let ts = std::fs::read_to_string(dir.join("schema.ts"))?;
    let overrides_path = root
        .join("xtask/overrides")
        .join(format!("{}.toml", revision.name));
    let overrides: overrides::Overrides = toml::from_str(
        &std::fs::read_to_string(&overrides_path)
            .with_context(|| format!("reading {}", overrides_path.display()))?,
    )
    .with_context(|| format!("parsing {}", overrides_path.display()))?;

    let deprecations = deprecations::parse(&ts);
    let model = ir::build(&schema, &overrides, &deprecations)?;
    let tokens = emit::emit(&model, revision);
    let file: syn::File = syn::parse2(tokens).context("emitted tokens are not valid Rust")?;
    let body = prettyplease::unparse(&file);

    let source = format!(
        "// @generated by `cargo xtask codegen` from MCP spec revision {} (commit {}).\n\
         // Do not edit by hand: change xtask/ or xtask/overrides/{}.toml instead.\n\n{body}",
        revision.name, revision.commit, revision.name
    );
    rustfmt(root, &source)
}

/// Formats with the workspace `rustfmt.toml`, so `cargo fmt --check` agrees
/// with the generated output.
fn rustfmt(root: &Path, source: &str) -> Result<String> {
    use std::io::Write as _;
    use std::process::{Command, Stdio};

    let mut child = Command::new("rustfmt")
        .arg("--config-path")
        .arg(root.join("rustfmt.toml"))
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("running rustfmt (install it with `rustup component add rustfmt`)")?;
    child
        .stdin
        .take()
        .context("rustfmt stdin unavailable")?
        .write_all(source.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        bail!(
            "rustfmt failed: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    Ok(normalize(&String::from_utf8(output.stdout)?))
}

fn normalize(text: &str) -> String {
    text.replace("\r\n", "\n")
}
