"""Generates the 200-tool catalog of the real-world benchmark, identically
for every SDK.

Usage: python bench/gen_tools.py

Writes:
- bench/servers/flymcprust/src/many.rs   (#[tool] functions + register())
- bench/servers/rmcp/src/many.rs         (one #[tool_router] impl)
- bench/fixtures/last_tool.json          (name and arguments of the last tool)

Tool `tool_NNN` takes 1 to 6 parameters whose types cycle through integers,
floats, strings, booleans, integer lists and optional strings, so the 200
input schemas differ. Everything is deterministic: rerunning produces the
same files.
"""

import json
from pathlib import Path

COUNT = 200
ROOT = Path(__file__).resolve().parent
TYPES = [
    ("i64", "integer", 7),
    ("f64", "number", 2.5),
    ("String", "string", "value"),
    ("bool", "boolean", True),
    ("Vec<i64>", "integer list", [1, 2, 3]),
    ("Option<String>", "optional string", "maybe"),
]
TOPICS = [
    "invoices", "contracts", "suppliers", "inventory", "shipments", "employees",
    "tickets", "payments", "budgets", "assets", "projects", "documents",
]
HEADER = "// Generated by bench/gen_tools.py; do not edit.\n"


def params(i):
    count = 1 + i % 6
    return [(f"p{j}", TYPES[(i + j) % len(TYPES)]) for j in range(count)]


def description(i):
    topic = TOPICS[i % len(TOPICS)]
    return f"Looks up {topic} record set {i} and returns a short status."


def flymcprust():
    out = [HEADER, "use flymcprust::ServerBuilder;\nuse flymcprust::prelude::*;\n\n"]
    for i in range(COUNT):
        name = f"tool_{i:03}"
        ps = params(i)
        out.append(f"/// {description(i)}\n///\n/// # Arguments\n///\n")
        for p, (_, kind, _) in ps:
            out.append(f"/// * `{p}` - An {kind} filter.\n" if kind[0] in "aeiou" else f"/// * `{p}` - A {kind} filter.\n")
        args = ", ".join(f"{p}: {t}" for p, (t, _, _) in ps)
        names = ", ".join(f"&{p}" for p, _ in ps)
        out.append(
            f"#[tool(read_only)]\npub fn {name}({args}) -> &'static str {{\n"
            f"    let _ = ({names},);\n    \"ok\"\n}}\n\n"
        )
    out.append("/// Registers the 200 tools.\n")
    out.append("pub fn register(builder: ServerBuilder) -> ServerBuilder {\n    builder\n")
    for i in range(COUNT):
        out.append(f"        .tool::<tool_{i:03}>()\n")
    out.append("}\n")
    return "".join(out)


def rmcp():
    out = [
        HEADER,
        "#![allow(dead_code)]\n",
        "use rmcp::handler::server::wrapper::Parameters;\n",
        "use rmcp::{schemars, tool, tool_router};\nuse serde::Deserialize;\n\n",
        "use crate::real::RealTools;\n\n",
    ]
    for i in range(COUNT):
        out.append(f"#[derive(Deserialize, schemars::JsonSchema)]\npub struct Args{i:03} {{\n")
        for p, (t, kind, _) in params(i):
            out.append(f"    /// A {kind} filter.\n    {p}: {t},\n")
        out.append("}\n\n")
    out.append("#[tool_router(router = many_router, vis = \"pub\")]\nimpl RealTools {\n")
    for i in range(COUNT):
        out.append(
            f"    #[tool(description = \"{description(i)}\")]\n"
            f"    fn tool_{i:03}(&self, Parameters(args): Parameters<Args{i:03}>) -> String {{\n"
            f"        let _ = args;\n        \"ok\".to_owned()\n    }}\n\n"
        )
    out.append("}\n")
    return "".join(out)


def last_tool():
    i = COUNT - 1
    return {"name": f"tool_{i:03}", "arguments": {p: v for p, (_, _, v) in params(i)}}


(ROOT / "servers/flymcprust/src/many.rs").write_text(flymcprust(), encoding="utf-8", newline="\n")
(ROOT / "servers/rmcp/src/many.rs").write_text(rmcp(), encoding="utf-8", newline="\n")
(ROOT / "fixtures/last_tool.json").write_text(json.dumps(last_tool(), indent=2) + "\n", encoding="utf-8", newline="\n")
print("wrote many.rs (2) and last_tool.json")
