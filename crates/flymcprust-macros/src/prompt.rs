//! Expansion of `#[prompt]`.

use proc_macro2::TokenStream;
use quote::quote;
use syn::{Error, Ident, ItemFn, LitStr};

use crate::docs;
use crate::params::{self, KeyValues, Options, Param};

const OPTIONS: Options = Options {
    macro_name: "prompt",
    schema_attrs: false,
    complete: true,
};

#[derive(Default)]
struct PromptArgs {
    name: Option<LitStr>,
    title: Option<LitStr>,
    description: Option<LitStr>,
    scopes: Option<Vec<LitStr>>,
}

fn parse_args(attr: TokenStream) -> syn::Result<PromptArgs> {
    let kv: KeyValues = syn::parse2(attr)?;
    if let Some(lit) = kv.positional {
        return Err(Error::new(
            lit.span(),
            "unexpected string; use `name = \"..\"` to rename the prompt",
        ));
    }
    let mut args = PromptArgs::default();
    for (key, value) in &kv.pairs {
        let slot = match key.to_string().as_str() {
            "name" => &mut args.name,
            "title" => &mut args.title,
            "description" => &mut args.description,
            "scopes" => {
                params::set_once(&mut args.scopes, key, params::scopes(key, value)?)?;
                continue;
            }
            _ => {
                return Err(Error::new(
                    key.span(),
                    "unknown `prompt` argument; expected `name`, `title`, `description` or \
                     `scopes`",
                ));
            }
        };
        params::set_once(slot, key, params::lit_str(key, value)?)?;
    }
    if let Some(name) = &args.name
        && (name.value().is_empty() || name.value().chars().any(char::is_control))
    {
        return Err(Error::new(
            name.span(),
            "prompt names cannot be empty or contain control characters",
        ));
    }
    Ok(args)
}

pub(crate) fn expand(attr: TokenStream, item: TokenStream) -> syn::Result<TokenStream> {
    let args = parse_args(attr)?;
    let mut func: ItemFn = syn::parse2(item)?;
    params::check_signature(&func, OPTIONS.macro_name)?;
    let params = params::collect_params(&mut func, &OPTIONS)?;
    let krate = params::krate();
    let scopes = params::scopes_call(args.scopes.as_ref());
    let fn_ident = &func.sig.ident;
    let vis = &func.vis;

    let (doc_description, arg_docs) = docs::split(&docs::doc_lines(&func.attrs));
    params::check_documented_args(&params, &arg_docs, fn_ident, "an argument of this prompt")?;
    let description = args
        .description
        .as_ref()
        .map(LitStr::value)
        .or(doc_description);

    let mut extract_args = Vec::new();
    let mut listed = Vec::new();
    for param in &params {
        let Param::Arg(arg) = param else { continue };
        let ident = &arg.ident;
        let ty = &arg.ty;
        let name = arg.name();
        let (parse, required) = match params::option_inner(ty) {
            Some(inner) => (
                quote!(let #ident: #ty = __args.optional::<#inner>(#name)?;),
                false,
            ),
            None => (
                quote!(let #ident: #ty = __args.required::<#ty>(#name)?;),
                true,
            ),
        };
        extract_args.push(parse);
        let doc = match params::arg_doc(arg, &arg_docs) {
            Some(d) => quote!(::core::option::Option::Some(::std::string::String::from(#d))),
            None => quote!(::core::option::Option::None),
        };
        listed.push(quote! {{
            let mut argument = #krate::spec::PromptArgument::new(::std::string::String::from(#name));
            argument.description = #doc;
            argument.required = ::core::option::Option::Some(#required);
            argument
        }});
    }

    let (call_args, injected) = params::call_args(&params);
    let extract = &injected.extract;
    let state_types = &injected.states;
    let (complete_fns, complete_regs) = params::completers(&params);

    // The handler is called through `__handler`, bound before the argument
    // locals: an argument named like the function (`fn user(user: User)`)
    // would otherwise shadow it.
    let call = if func.sig.asyncness.is_some() {
        quote!(__handler(#(#call_args),*).await)
    } else {
        quote!(__handler(#(#call_args),*))
    };

    let name = match &args.name {
        Some(lit) => lit.value(),
        None => fn_ident.to_string().trim_start_matches("r#").to_owned(),
    };
    let set_description = description.map(|d| {
        quote! { prompt.description = ::core::option::Option::Some(::std::string::String::from(#d)); }
    });
    let set_title = args.title.as_ref().map(|t| {
        quote! { prompt.title = ::core::option::Option::Some(::std::string::String::from(#t)); }
    });
    let set_arguments = (!listed.is_empty()).then(|| {
        quote! { prompt.arguments = ::core::option::Option::Some(::std::vec![#(#listed),*]); }
    });

    let auto_register = auto_register(fn_ident);
    let marker_doc = format!(" MCP prompt marker for [`{fn_ident}()`], generated by `#[prompt]`.");

    Ok(quote! {
        #func

        #[doc = #marker_doc]
        #[allow(non_camel_case_types)]
        #vis struct #fn_ident {}

        impl #krate::Prompt for #fn_ident {
            fn definition() -> #krate::PromptDef {
                #[allow(unused_variables, non_snake_case, clippy::needless_pass_by_value)]
                fn __get(
                    __args: &#krate::PromptArguments,
                    __ctx: #krate::Ctx,
                ) -> ::core::result::Result<#krate::PromptFuture, #krate::ToolError> {
                    let __handler = #fn_ident;
                    #(#extract_args)*
                    #(#extract)*
                    ::core::result::Result::Ok(::std::boxed::Box::pin(async move {
                        #krate::IntoPromptResult::into_prompt_result(#call)
                    }))
                }
                #(#complete_fns)*

                let mut prompt = #krate::spec::Prompt::new(::std::string::String::from(#name));
                #set_description
                #set_title
                #set_arguments
                #krate::PromptDef::new(prompt, __get)
                    #scopes
                    #(.require_state::<#state_types>())*
                    #(#complete_regs)*
            }
        }

        #auto_register
    })
}

#[cfg(feature = "auto-register")]
fn auto_register(fn_ident: &Ident) -> TokenStream {
    let krate = params::krate();
    quote! {
        #krate::inventory::submit! {
            #krate::AutoPrompt::new(<#fn_ident as #krate::Prompt>::definition)
        }
    }
}

#[cfg(not(feature = "auto-register"))]
fn auto_register(_: &Ident) -> TokenStream {
    TokenStream::new()
}
